"""Export the locked runtime for pip-based hosts, including the CPU wheel source."""

from __future__ import annotations

from pathlib import Path
import subprocess


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    exported = subprocess.run(
        ["uv", "export", "--locked", "--no-dev", "--no-emit-project", "--no-header"],
        cwd=root, check=True, capture_output=True, text=True,
    )
    content = "# Generated by python -m tools.export_requirements\n--find-links https://download.pytorch.org/whl/cpu/torch/\n" + exported.stdout
    (root / "requirements.txt").write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
